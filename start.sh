#!/bin/sh
# Сайты часто меняются, и yt-dlp каждый раз под них подстраивается.
# Поэтому при каждом запуске берём свежие версии, а не те, что были при сборке образа.
pip install -q -U "yt-dlp[default,curl-cffi]" gallery-dl \
  || echo "Не удалось обновить yt-dlp, работаем с версией из образа"
exec python bot.py
